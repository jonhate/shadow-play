def h(text, level=1):
    p = doc.add_heading(text, level=level)
    for r in p.runs:
        r.font.name = EN
        r._element.rPr.rFonts.set(qn("w:eastAsia"), CN)
        r.font.color.rgb = DARK
        r.font.size = Pt(15 if level == 1 else 12.5)
    p.paragraph_format.space_before = Pt(14 if level == 1 else 10)
    p.paragraph_format.space_after = Pt(5)
    return p


def p(text, bold=False, size=10.5, color=DARK, indent=0, spacing=1.55):
    par = doc.add_paragraph()
    if indent:
        par.paragraph_format.left_indent = Cm(indent)
    par.paragraph_format.line_spacing = spacing
    r = par.add_run(text)
    r.font.name = EN
    r._element.rPr.rFonts.set(qn("w:eastAsia"), CN)
    r.font.size = Pt(size)
    r.bold = bold
    r.font.color.rgb = color
    return par


def bullet(text, size=10.5):
    par = doc.add_paragraph(style="List Bullet")
    par.paragraph_format.line_spacing = 1.45
    par.paragraph_format.space_after = Pt(2)
    r = par.add_run(text)
    r.font.name = EN
    r._element.rPr.rFonts.set(qn("w:eastAsia"), CN)
    r.font.size = Pt(size)
    return par


def table(rows, widths, size=9.5, header=True):
    t = doc.add_table(rows=0, cols=len(rows[0]))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, row in enumerate(rows):
        cells = t.add_row().cells
        for j, val in enumerate(row):
            cells[j].text = ""
            par = cells[j].paragraphs[0]
            par.paragraph_format.line_spacing = 1.2
            par.paragraph_format.space_after = Pt(1)
            r = par.add_run(str(val))
            r.font.name = EN
            r._element.rPr.rFonts.set(qn("w:eastAsia"), CN)
            r.font.size = Pt(size)
            r.bold = header and i == 0
    for row in t.rows:
        for j, w in enumerate(widths):
            row.cells[j].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


