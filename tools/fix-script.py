import re

path = 'docs/评审视频讲稿与分镜.md'
t = open(path, encoding='utf-8').read()

new = '''# 第二部分：完整配音讲稿

> 旁白约 950 字，正常语速约 3 分 25 秒；配合约 50 秒无旁白演示画面，成片约 4:15。
> `〔画面〕` 内为提示，不朗读。

〔0:00–0:18｜无旁白〕
画面：真人举起双手，幕上皮影随之抬手、两手一合作揖；切到"亮相"定格。
字幕：**举起双手，皮影跟着你动。**

〔0:18–0:50｜定位与背景〕
皮影戏是入选联合国教科文组织人类非物质文化遗产代表作名录的传统戏剧。
它的魅力不在看，而在耍——艺人一手执三根竹签，一根撑头颈身，两根挑双手，
靠拇指食指搓动签杆改变关节朝向，靠抬落平衡杆让皮影进退。
但这门手艺要练很多年，观众在展厅里通常只能隔着玻璃看。
我们想做的，是让观众站到幕布前，用自己的手，把一台皮影戏演出来。

〔0:50–1:45｜核心创新〕
第一个创新，是我们没把"手势"当成翻页开关，而是把三根竹签的操作逻辑搬到了手上。
张开手掌，皮影的手跟着你走；握拳，这只手就执签定住；两手一合是作揖，双手举高是亮相；
手掌左右平移，皮影就迈步走位。
进一步，我们还按传统握法做了一套手指模式：拇指食指捏住，等于夹住一根竹签；
两指连线转动，就是传统里的搓签，皮影的手腕会跟着转。
第二个创新，是动作即台词。台词不按时间轴自动播完：
屏幕上浮出提示，比如"两手一合·作揖"，你必须真的做出来，戏才往下走一句；
做对了，提示变绿打勾，还给一记锣鼓。观众为了看下一句，会主动去学这个动作。

〔1:45–3:20｜关键实现与实际成果〕
（约 10 秒无旁白：完整交互链路——举手、跟手、作揖推进、亮相）

舞台上没有预制动画。每个皮影都是分件、关节加竹签的结构，我们逐帧计算每个部件的变换：
肩和肘用两段骨骼的逆解求解，手腕跟随手部关键点，所以皮影的手是真的在够你的手。
同一套骨架可以切三种皮：剪影、镂空、套色。

内容上做了六出戏，三出原创、三出改编自西厢记、霸王别姬和八仙过海，一共二十五个剧情节拍。
六出演完，会自己演一段二十四秒的谢幕，不需要人管。
第一次来的人不会用，所以有教学关：五步，每一步都必须真的做出来才通过。

声音上，六出戏各配一段戏剧原声——昆曲牡丹亭、将军令、夜深沉、水龙吟、万年欢、良宵引。
换幕时旧曲淡出、新曲淡入；作揖、亮相这些动作有对应的锣鼓音效。
原声里本身有唱腔，所以台词配音默认关闭，避免两层人声打架。

现场落地做了三件事：一键启动并自动打开浏览器；展馆模式全屏、隐藏鼠标、屏蔽右键、出错自动重载；
还有摄像头自检、音频自检和实时诊断面板，不接技术也能看出问题在哪。

〔3:20–4:05｜创作过程与原创贡献〕
开发时我们先把传统握签的资料读清楚，也对比了现有的手势互动作品——
大部分是挥手翻页、隔空点击，和皮影的操作逻辑没有关系。
所以放弃了几种看起来更炫的做法：没有做五指各控一根签，因为普通摄像头对小指无名指抖动太大；
也没有把台词做成自动播放，那样观众就只是看客。
测试上，我们写脚本逐项验证：五步教学能否通过、剧情节拍会不会连跳、音频电平是否一致、
不同分辨率下按钮会不会挡住标题；真机上用摄像头反复调执签和捏合的灵敏度。
需要说明的是，代码是在 AI 编程助手的协助下完成的；
选题、交互设计、素材选用与授权、测试验收和部署，由我完成。

〔4:05–4:20｜价值收束〕
它不需要深度相机，也不需要穿戴设备，一台普通笔记本加一个摄像头就能跑，断网也能用；
换一套皮影资产，就能换一批角色。对非遗展陈来说，它把"看戏"变成了"学艺"。

---

'''

i = t.find('# 第二部分')
j = t.find('# 第三部分')
t = t[:i] + new + t[j:]
open(path, 'w', encoding='utf-8').write(t)

body = t[t.find('# 第二部分'):t.find('# 第三部分')]
body = re.sub(r'〔[^〕]*〕', '', body)
body = re.sub(r'^>.*$', '', body, flags=re.M)
body = body.replace('第二部分：完整配音讲稿', '')
n = len(re.sub(r'\s', '', body))
print(f'旁白字数 {n} → 约 {round(n/4.5)} 秒 = {round(n/4.5/60,1)} 分钟；加 50 秒留白 ≈ {round(n/4.5/60+0.83,1)} 分钟')
